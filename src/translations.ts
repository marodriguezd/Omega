declare global {
  interface Window {
    translations?: Record<string, Record<string, string>>;
    bubbleTranslations?: Record<string, Record<string, string>>;
    hydroTranslations?: Record<string, Record<string, string>>;
  }
}

export function initAllTranslations() {
  const current = window.translations || {};
  const bubble = window.bubbleTranslations || {};
  const hydro = window.hydroTranslations || {};
  const langs = ['es', 'en', 'fr', 'de', 'it', 'pt', 'zh'];
  const merged: Record<string, Record<string, string>> = {};

  langs.forEach(lang => {
    merged[lang] = {
      ...(bubble[lang] || {}),
      ...(hydro[lang] || {}),
      ...(current[lang] || {}),
      ...(HUB_TRANSLATIONS[lang] || HUB_TRANSLATIONS['es'])
    };
  });

  window.translations = merged;
}

export function getActiveTranslation(key: string, defaultVal: string): string {
  if (typeof window === 'undefined') return defaultVal;
  let lang = localStorage.getItem('omega_language');
  if (!lang) {
    try {
      lang = JSON.parse(localStorage.getItem('bubbleBreathingConfig') || '{}').language;
    } catch (_) {}
  }
  const activeLang = lang || 'es';
  return (
    window.translations?.[activeLang]?.[key] ||
    HUB_TRANSLATIONS[activeLang]?.[key] ||
    HUB_TRANSLATIONS['es']?.[key] ||
    defaultVal
  );
}
